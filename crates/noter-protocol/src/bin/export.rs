//! `cargo run -p noter-protocol --bin noter-contract-export [-- <repo-root>]`
//!
//! Writes every generated contract artefact. Run it after any change to the
//! crate and commit the output; CI runs it with `--check` and fails on a diff.
//!
//! * `apps/desktop/src/core/bindings.ts`   TypeScript types, command/event maps, typed client
//! * `contracts/ipc.manifest.json`         commands, events, error codes as data
//! * `contracts/engine.schema.json`        engine stdio protocol (→ Swift Codable)
//! * `contracts/mcp-tools.schema.json`     noter-mcp tool input/output schemas
//! * `contracts/skills/*.schema.json`      LLM skill output schemas
//! * `contracts/fixtures/world.json`       typed fixtures for the fake core

use std::path::{Path, PathBuf};

use noter_protocol::ipc::{COMMANDS, EVENTS};
use noter_protocol::{engine, ipc, mcp, skills, ErrorCode, CONTRACT_VERSION};
use schemars::schema_for;
use serde_json::{json, Value};

fn ty(s: &str) -> String {
    s.replace(' ', "")
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for c in s.chars() {
        if c == '_' {
            up = true;
        } else if up {
            out.extend(c.to_uppercase());
            up = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn snake_json<T: serde::Serialize>(v: &T) -> String {
    serde_json::to_value(v)
        .unwrap()
        .as_str()
        .unwrap()
        .to_string()
}

fn ts_doc(doc: &str, indent: &str) -> String {
    let lines: Vec<&str> = doc
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect();
    if lines.is_empty() {
        return String::new();
    }
    let mut s = format!("{indent}/**\n");
    for l in lines {
        s.push_str(&format!("{indent} * {l}\n"));
    }
    s.push_str(&format!("{indent} */\n"));
    s
}

fn bindings_ts() -> String {
    let types = ipc::ipc_types().register::<noter_protocol::fixtures::FakeWorld>();
    let body = specta_typescript::Typescript::default()
        .header("// GENERATED by `cargo run -p noter-protocol --bin noter-contract-export`. Do not edit.\n// Source of truth: crates/noter-protocol (ADR-0001). Contract: docs/DESIGN-core.md 3.3.\n/* eslint-disable */")
        .export(&types, specta_serde::Format)
        .expect("typescript export");

    let mut s = body;
    s.push_str("\n// ───────────────────────── contract surface ─────────────────────────\n\n");
    s.push_str(&format!(
        "export const CONTRACT_VERSION = \"{CONTRACT_VERSION}\";\n\n"
    ));
    s.push_str("export type Result<T, E = CoreError> = { status: \"ok\"; data: T } | { status: \"error\"; error: E };\n\n");

    // command metadata
    s.push_str("/** Every command: group, stability and the windows allowed to call it (PM-08). */\nexport const COMMANDS = {\n");
    for c in COMMANDS {
        let windows: Vec<String> = c
            .windows
            .iter()
            .map(|w| format!("\"{}\"", w.as_str()))
            .collect();
        s.push_str(&format!(
            "  {}: {{ group: \"{}\", stability: \"{}\", windows: [{}], channel: {} }},\n",
            c.name,
            snake_json(&c.group),
            snake_json(&c.stability),
            windows.join(", "),
            c.channel.is_some()
        ));
    }
    s.push_str("} as const satisfies Record<string, { group: CommandGroup; stability: Stability; windows: readonly WindowLabel[]; channel: boolean }>;\n\n");
    s.push_str("export type CommandName = keyof typeof COMMANDS;\n\n");

    s.push_str("export interface CommandArgs {\n");
    for c in COMMANDS {
        s.push_str(&format!("  {}: {};\n", c.name, ty(c.args)));
    }
    s.push_str("}\n\nexport interface CommandResults {\n");
    for c in COMMANDS {
        s.push_str(&format!("  {}: {};\n", c.name, ty(c.result)));
    }
    s.push_str("}\n\n/** Message type of each subscribing command's Channel. */\nexport interface ChannelMessages {\n");
    for c in COMMANDS.iter().filter(|c| c.channel.is_some()) {
        s.push_str(&format!("  {}: {};\n", c.name, ty(c.channel.unwrap())));
    }
    s.push_str("}\n\nexport type ChannelCommand = keyof ChannelMessages;\n\n");

    // events
    s.push_str("/** Payload of each event (Tauri events, broadcast to every window). */\nexport interface EventPayloads {\n");
    for e in EVENTS {
        s.push_str(&ts_doc(e.doc, "  "));
        s.push_str(&format!("  \"{}\": {};\n", e.name, ty(e.payload)));
    }
    s.push_str("}\n\nexport type EventName = keyof EventPayloads;\n\nexport const EVENTS = {\n");
    for e in EVENTS {
        s.push_str(&format!(
            "  \"{}\": {{ stability: \"{}\" }},\n",
            e.name,
            snake_json(&e.stability)
        ));
    }
    s.push_str("} as const satisfies Record<EventName, { stability: Stability }>;\n\n");

    let codes: Vec<String> = ErrorCode::ALL
        .iter()
        .map(|c| format!("\"{}\"", snake_json(c)))
        .collect();
    s.push_str(&format!(
        "export const ERROR_CODES: readonly ErrorCode[] = [{}];\n\n",
        codes.join(", ")
    ));

    // transport + client
    s.push_str(r#"/**
 * The bridge's only seam (DESIGN › Core bridge). `tauri-transport.ts` implements it
 * over Tauri IPC; `fake/fake-core.ts` implements it in memory for UI-only work and tests.
 * `invoke` rejects with a `CoreError`.
 */
export interface Transport {
  invoke(cmd: CommandName, args: unknown, onMessage?: (message: unknown) => void): Promise<unknown>;
  listen(event: EventName, handler: (payload: unknown) => void): Promise<() => void>;
}

export function isCoreError(e: unknown): e is CoreError {
  return typeof e === "object" && e !== null && "code" in e && "retryable" in e;
}

function toCoreError(e: unknown): CoreError {
  if (isCoreError(e)) return e;
  return { code: "internal", message: e instanceof Error ? e.message : String(e), retryable: true, detail: null };
}

/** Typed client. One method per command; every method resolves to a `Result`, never throws. */
export function createCore(transport: Transport) {
  async function call<K extends CommandName>(
    cmd: K,
    args: CommandArgs[K],
    onMessage?: (message: never) => void,
  ): Promise<Result<CommandResults[K]>> {
    try {
      const data = await transport.invoke(cmd, args, onMessage as ((m: unknown) => void) | undefined);
      return { status: "ok", data: data as CommandResults[K] };
    } catch (e) {
      return { status: "error", error: toCoreError(e) };
    }
  }
  return {
"#);
    for c in COMMANDS {
        s.push_str(&ts_doc(c.doc, "    "));
        match c.channel {
            Some(ch) => s.push_str(&format!(
                "    {}: (args: {}, onMessage: (message: {}) => void) => call(\"{}\", args, onMessage),\n",
                camel(c.name),
                ty(c.args),
                ty(ch),
                c.name
            )),
            None => s.push_str(&format!("    {}: (args: {}) => call(\"{}\", args),\n", camel(c.name), ty(c.args), c.name)),
        }
    }
    s.push_str(
        r#"    /** Subscribe to an event; resolves to the unsubscribe function. */
    on: <E extends EventName>(event: E, handler: (payload: EventPayloads[E]) => void) =>
      transport.listen(event, handler as (payload: unknown) => void),
  };
}

export type Core = ReturnType<typeof createCore>;
"#,
    );
    s
}

fn manifest() -> Value {
    let commands: Vec<Value> = COMMANDS
        .iter()
        .map(|c| {
            json!({
                "name": c.name,
                "group": c.group,
                "stability": c.stability,
                "windows": c.windows.iter().map(|w| w.as_str()).collect::<Vec<_>>(),
                "args": ty(c.args),
                "result": ty(c.result),
                "channel": c.channel.map(ty),
                "doc": c.doc.trim(),
            })
        })
        .collect();
    let events: Vec<Value> = EVENTS
        .iter()
        .map(|e| json!({ "name": e.name, "payload": ty(e.payload), "stability": e.stability, "doc": e.doc.trim() }))
        .collect();
    json!({
        "contract_version": CONTRACT_VERSION,
        "engine_protocol_version": engine::ENGINE_PROTOCOL_VERSION,
        "commands": commands,
        "events": events,
        "error_codes": ErrorCode::ALL,
        "mcp_tools": mcp::TOOLS.iter().map(|(n, w)| json!({"name": n, "writes": w})).collect::<Vec<_>>(),
    })
}

fn mcp_schemas() -> Value {
    use mcp::*;
    macro_rules! tool {
        ($i:ty, $o:ty) => {
            json!({ "input": schema_for!($i), "output": schema_for!($o) })
        };
    }
    json!({
        "search_calls": tool!(SearchCallsInput, SearchCallsOutput),
        "search_documents": tool!(SearchDocumentsInput, SearchDocumentsOutput),
        "get_transcript_span": tool!(GetTranscriptSpanInput, GetTranscriptSpanOutput),
        "get_person": tool!(GetPersonInput, GetPersonOutput),
        "get_decisions": tool!(GetDecisionsInput, ItemsOutput),
        "get_open_items": tool!(GetOpenItemsInput, ItemsOutput),
        "get_screen_context": tool!(GetScreenContextInput, ScreenContextOutput),
        "pin_item": tool!(PinItemInput, StagedOutput),
        "propose_correction": tool!(ProposeCorrectionInput, StagedOutput),
        "emit_card": tool!(EmitCardInput, StagedOutput),
        "$socket": { "request": schema_for!(CoreSocketRequest), "response": schema_for!(CoreSocketResponse) },
    })
}

fn write(root: &Path, rel: &str, content: &str, check: bool, diffs: &mut Vec<String>) {
    let p = root.join(rel);
    if check {
        let old = std::fs::read_to_string(&p).unwrap_or_default();
        if old != content {
            diffs.push(rel.to_string());
        }
        return;
    }
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(&p, content).unwrap();
    println!("wrote {rel}");
}

fn pretty(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(v).unwrap();
    s.push('\n');
    s
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let check = args.iter().any(|a| a == "--check");
    let root = args
        .iter()
        .find(|a| !a.starts_with("--"))
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../.."));
    let mut diffs = Vec::new();

    write(
        &root,
        "apps/desktop/src/core/bindings.ts",
        &bindings_ts(),
        check,
        &mut diffs,
    );
    write(
        &root,
        "contracts/ipc.manifest.json",
        &pretty(&manifest()),
        check,
        &mut diffs,
    );
    let engine = json!({
        "protocol_version": engine::ENGINE_PROTOCOL_VERSION,
        "command_line": schema_for!(engine::EngineCommandLine),
        "event_line": schema_for!(engine::EngineEventLine),
    });
    write(
        &root,
        "contracts/engine.schema.json",
        &pretty(&engine),
        check,
        &mut diffs,
    );
    write(
        &root,
        "contracts/mcp-tools.schema.json",
        &pretty(&mcp_schemas()),
        check,
        &mut diffs,
    );
    let skills_out: [(&str, Value); 6] = [
        (
            "council-tick",
            serde_json::to_value(schema_for!(skills::CouncilTickOutput)).unwrap(),
        ),
        (
            "post-call",
            serde_json::to_value(schema_for!(skills::PostCallOutput)).unwrap(),
        ),
        (
            "role-review",
            serde_json::to_value(schema_for!(skills::RoleReviewOutput)).unwrap(),
        ),
        (
            "handoff",
            serde_json::to_value(schema_for!(skills::HandoffPromptOutput)).unwrap(),
        ),
        (
            "ask-answer",
            serde_json::to_value(schema_for!(skills::AskAnswerOutput)).unwrap(),
        ),
        (
            "reconcile",
            serde_json::to_value(schema_for!(skills::ReconcileJudgementOutput)).unwrap(),
        ),
    ];
    for (name, schema) in skills_out {
        write(
            &root,
            &format!("contracts/skills/{name}.schema.json"),
            &pretty(&schema),
            check,
            &mut diffs,
        );
    }
    let world = serde_json::to_value(noter_protocol::fixtures::world()).unwrap();
    write(
        &root,
        "contracts/fixtures/world.json",
        &pretty(&world),
        check,
        &mut diffs,
    );

    if check {
        if diffs.is_empty() {
            println!("contract artefacts are up to date");
        } else {
            eprintln!(
                "out of date (run the exporter and commit): {}",
                diffs.join(", ")
            );
            std::process::exit(1);
        }
    }
}
