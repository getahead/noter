fn ty(s: &str) -> String {
    s.replace(' ', "")
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for c in s.chars() {
        if c == '_' {
            up = true;
        } else if up {
            out.extend(c.to_uppercase());
            up = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn snake_json<T: serde::Serialize>(v: &T) -> String {
    serde_json::to_value(v)
        .unwrap()
        .as_str()
        .unwrap()
        .to_string()
}

/// A Constructor Studio scope marker line for the generated TypeScript (`@cpt-{kind}:{id}:p1`).
/// Built here, not written out literally, so this generator does not count as implementing the ID.
fn cpt_marker(kind: &str, id: &str) -> String {
    format!("// @cpt-{kind}:{id}:p1\n")
}

fn ts_doc(doc: &str, indent: &str) -> String {
    let lines: Vec<&str> = doc
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect();
    if lines.is_empty() {
        return String::new();
    }
    let mut s = format!("{indent}/**\n");
    for l in lines {
        s.push_str(&format!("{indent} * {l}\n"));
    }
    s.push_str(&format!("{indent} */\n"));
    s
}

